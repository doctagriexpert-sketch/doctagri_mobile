import 'package:injectable/injectable.dart';

enum AppLanguage { french, ewe, kabye }

@lazySingleton
class LanguageService extends ChangeNotifier {
  static const String _boxName = 'language_prefs';
  static const String _langKey = 'selected_language';

  AppLanguage _currentLanguage = AppLanguage.french;
  Box? _box;

  AppLanguage get currentLanguage => _currentLanguage;

  String get languageCode => switch (_currentLanguage) {
    AppLanguage.french => 'fr',
    AppLanguage.ewe => 'ee',
    AppLanguage.kabye => 'kab',
  };

  String get languageName => switch (_currentLanguage) {
    AppLanguage.french => 'Français',
    AppLanguage.ewe => 'Ewe',
    AppLanguage.kabye => 'Kabyè',
  };

  Future<void> initialize() async {
    _box = await Hive.openBox(_boxName);
    final saved = _box?.get(_langKey, defaultValue: 'fr');
    _currentLanguage = switch (saved) {
      'ee' => AppLanguage.ewe,
      'kab' => AppLanguage.kabye,
      _ => AppLanguage.french,
    };
  }

  Future<void> setLanguage(AppLanguage language) async {
    _currentLanguage = language;
    await _box?.put(_langKey, languageCode);
    notifyListeners();
  }

  String getCurrentLanguage() => languageCode;

  String getLanguageName() => languageName;

  List<AppLanguage> get supportedLanguages => AppLanguage.values;

  String t(String key) {
    final translations = _translations[languageCode] ?? _translations['fr']!;
    return translations[key] ?? key;
  }

  String translateTerm(String term) {
    final terms = _agriculturalTerms[languageCode] ?? _agriculturalTerms['fr']!;
    return terms[term.toLowerCase()] ?? term;
  }

